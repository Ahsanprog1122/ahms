"""Base classes and supporting data structures for the AHMS Analytics Engine.

Strictly pure Python, using Decimal for all monetary math.
"""

from abc import ABC, abstractmethod
from datetime import date
from decimal import Decimal
from typing import List, Optional


class AssetValuation:
    """Represents a point-in-time valuation for an asset."""

    def __init__(
        self,
        valuation_date: date,
        value: Decimal,
        source: str = "manual",
        notes: str = "",
    ):
        self.valuation_date = valuation_date
        self.value = Decimal(str(value))
        self.source = source
        self.notes = notes

    def __repr__(self) -> str:
        return f"<AssetValuation date={self.valuation_date} value={self.value} source={self.source}>"


class Transaction:
    """Represents a buy, sell, or expense transaction."""

    def __init__(
        self,
        transaction_date: date,
        transaction_type: str,
        quantity: Decimal,
        price_per_unit: Decimal,
        fees: Decimal = Decimal("0"),
        notes: str = "",
    ):
        self.transaction_date = transaction_date
        self.transaction_type = transaction_type.lower()
        self.quantity = Decimal(str(quantity))
        self.price_per_unit = Decimal(str(price_per_unit))
        self.fees = Decimal(str(fees))
        self.notes = notes

    @property
    def total_amount(self) -> Decimal:
        """Total transaction cash flow."""
        base = self.quantity * self.price_per_unit
        if self.transaction_type == "buy":
            return base + self.fees
        elif self.transaction_type == "sell":
            return base - self.fees
        return self.fees

    def __repr__(self) -> str:
        return f"<Transaction {self.transaction_type} qty={self.quantity} @ {self.price_per_unit}>"


class IncomeRecord:
    """Base class for income generated by an asset."""

    def __init__(
        self,
        record_date: date,
        amount: Decimal,
        income_type: str = "income",
        notes: str = "",
    ):
        self.record_date = record_date
        self.amount = Decimal(str(amount))
        self.income_type = income_type
        self.notes = notes

    def __repr__(self) -> str:
        return f"<{self.__class__.__name__} date={self.record_date} amount={self.amount}>"


class Dividend(IncomeRecord):
    """Dividend income from stocks or funds."""

    def __init__(self, record_date: date, amount: Decimal, notes: str = ""):
        super().__init__(record_date, amount, income_type="dividend", notes=notes)


class InterestIncome(IncomeRecord):
    """Interest income from bonds or cash accounts."""

    def __init__(self, record_date: date, amount: Decimal, notes: str = ""):
        super().__init__(record_date, amount, income_type="interest", notes=notes)


class Asset(ABC):
    """Abstract base class for all assets in AHMS.

    Encapsulates core properties and mandates contract methods.
    """

    def __init__(
        self,
        name: str,
        purchase_price: Decimal,
        purchase_date: date,
        quantity: Decimal = Decimal("1"),
        costs: Decimal = Decimal("0"),
        asset_id: Optional[str] = None,
    ):
        self.name = name
        self.purchase_price = Decimal(str(purchase_price))
        self.purchase_date = purchase_date
        self.quantity = Decimal(str(quantity))
        self.costs = Decimal(str(costs))
        self.asset_id = asset_id

        # Supporting history
        self.valuations: List[AssetValuation] = []
        self.transactions: List[Transaction] = []
        self.income_records: List[IncomeRecord] = []

    @property
    @abstractmethod
    def category(self) -> str:
        """Returns the asset category (e.g. 'stocks', 'real_estate', 'gold', 'cash')."""
        pass

    @property
    @abstractmethod
    def is_liquid(self) -> bool:
        """Indicates whether this asset qualifies as liquid."""
        pass

    @abstractmethod
    def current_value(self) -> Decimal:
        """Calculate and return the current market value in PKR."""
        pass

    def total_cost_basis(self) -> Decimal:
        """Initial cost basis = (quantity * purchase_price) + costs."""
        return (self.quantity * self.purchase_price) + self.costs

    def gain(self) -> Decimal:
        """Total gain/loss = current_value() - total_cost_basis()."""
        return self.current_value() - self.total_cost_basis()

    def annual_income(self, as_of: Optional[date] = None) -> Decimal:
        """Sum of all income received in the last 12 months (365 days) up to as_of."""
        ref_date = as_of or date.today()
        one_year_ago = ref_date.replace(year=ref_date.year - 1) if not (ref_date.month == 2 and ref_date.day == 29) else ref_date.replace(year=ref_date.year - 1, day=28)

        total = Decimal("0")
        for inc in self.income_records:
            if one_year_ago <= inc.record_date <= ref_date:
                total += inc.amount
        return total

    def add_valuation(self, valuation_date: date, value: Decimal, source: str = "manual", notes: str = "") -> None:
        """Record a historical or current valuation (append-only)."""
        val = AssetValuation(valuation_date, value, source, notes)
        self.valuations.append(val)
        self.valuations.sort(key=lambda x: x.valuation_date)

    def latest_valuation(self) -> Optional[AssetValuation]:
        """Get the most recent valuation record, if any."""
        return self.valuations[-1] if self.valuations else None

    def peak_valuation_value(self) -> Decimal:
        """Return the maximum recorded valuation or current value."""
        values = [v.value for v in self.valuations]
        values.append(self.current_value())
        values.append(self.total_cost_basis())
        return max(values)

    def __repr__(self) -> str:
        return f"<{self.__class__.__name__} name='{self.name}' value={self.current_value()}>"


class FinancialAsset(Asset, ABC):
    """Abstract base class for financial assets (stocks, bonds, funds, cash)."""

    @property
    def is_liquid(self) -> bool:
        return True


class PhysicalAsset(Asset, ABC):
    """Abstract base class for physical assets (real estate, land, vehicles)."""

    @property
    def is_liquid(self) -> bool:
        return False
